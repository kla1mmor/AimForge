-- AimForge leaderboard schema (Cloudflare D1 / SQLite)
CREATE TABLE IF NOT EXISTS players (
  pid         TEXT PRIMARY KEY,          -- random 128-bit id generated by the game (hex)
  secret_hash TEXT NOT NULL,             -- sha256 of the player's random secret
  name        TEXT NOT NULL,
  name_key    TEXT NOT NULL UNIQUE,      -- lower-cased name, nicknames are unique
  created     INTEGER NOT NULL,
  last_submit INTEGER NOT NULL DEFAULT 0,
  runs        INTEGER NOT NULL DEFAULT 0,
  banned      INTEGER NOT NULL DEFAULT 0
);

-- best result per player per scenario per ruleset (ruleset = hash of default scenario params)
CREATE TABLE IF NOT EXISTS best (
  scenario TEXT NOT NULL,
  ruleset  TEXT NOT NULL,
  pid      TEXT NOT NULL,
  score    REAL NOT NULL,
  acc      REAL NOT NULL,
  kills    INTEGER NOT NULL,
  ttk      REAL NOT NULL,
  runs     INTEGER NOT NULL DEFAULT 1,
  at       INTEGER NOT NULL,
  ver      TEXT,
  PRIMARY KEY (scenario, ruleset, pid)
);
CREATE INDEX IF NOT EXISTS best_rank ON best (scenario, ruleset, score DESC);
CREATE INDEX IF NOT EXISTS best_pid  ON best (pid, ruleset);

CREATE TABLE IF NOT EXISTS ip_rate (
  ip  TEXT PRIMARY KEY,                  -- sha256(ip) — raw IPs are not stored
  win INTEGER NOT NULL,
  n   INTEGER NOT NULL
);
