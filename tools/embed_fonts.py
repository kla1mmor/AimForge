#!/usr/bin/env python3
"""Generate src/fonts_data.c from assets/fonts/*.ttf (fonts are embedded into the exe)."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [
    ("font_medium", "Montserrat-Medium.ttf"),
    ("font_semibold", "Montserrat-SemiBold.ttf"),
    ("font_bold", "Montserrat-Bold.ttf"),
    ("font_mono", "JBMono-Bold.ttf"),
]


def main() -> int:
    out = os.path.join(ROOT, "src", "fonts_data.c")
    srcs = [os.path.join(ROOT, "assets", "fonts", f) for _, f in FONTS]
    if os.path.exists(out) and all(os.path.getmtime(out) >= os.path.getmtime(s) for s in srcs):
        return 0
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/embed_fonts.py — do not edit.\n")
        f.write("// Montserrat, JetBrains Mono: SIL Open Font License 1.1\n")
        for (name, _), path in zip(FONTS, srcs):
            data = open(path, "rb").read()
            f.write(f"const unsigned char {name}[{len(data)}] = {{\n")
            for i in range(0, len(data), 24):
                f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
            f.write("};\n")
            f.write(f"const int {name}_len = {len(data)};\n")
    print("generated", os.path.relpath(out, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
